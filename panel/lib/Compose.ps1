# Generates the compose files and the nginx config the panel actually runs.
#
# Why generate instead of editing samples/docker-compose.<year>.yml:
#   - the shipped samples stay untouched, so `git status` stays clean;
#   - settings (port, data folder) have somewhere to land.
# Every compose call passes -p <composeProject> ("samples" by default), which
# keeps the image name samples-rs<year> and the container name rs<year>. Without
# that, moving the file to another folder would rename the project and force a
# ~14 GB rebuild of an image that is already on disk.

Set-StrictMode -Version 1.0

function ConvertTo-ComposePath {
    param([string]$Path)
    return ($Path -replace '\\', '/')
}

function ConvertTo-YamlSingleQuoted {
    param([string]$Value)
    return "'" + ($Value -replace "'", "''") + "'"
}

function Get-VersionComposePath {
    param([string]$ComposeDir, [int]$Year)
    return (Join-Path $ComposeDir "docker-compose.$Year.yml")
}

function Get-ProxyComposePath {
    param([string]$ComposeDir)
    return (Join-Path $ComposeDir 'docker-compose.proxy.yml')
}

function Get-ProxyNginxPath {
    param([string]$ComposeDir)
    return (Join-Path $ComposeDir 'proxy/nginx.conf')
}

function Initialize-VersionDataDir {
    param($Version)

    $dir = [string]$Version.dataDir
    if ([string]::IsNullOrWhiteSpace($dir)) { return $false }
    if (-not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    return $true
}

function Write-VersionCompose {
    param(
        [Parameter(Mandatory = $true)]$Config,
        [Parameter(Mandatory = $true)]$Version,
        [Parameter(Mandatory = $true)][string]$RepoRoot,
        [Parameter(Mandatory = $true)][string]$ComposeDir
    )

    $year = [int]$Version.year
    $buildContext = ConvertTo-ComposePath (Join-Path (Join-Path $RepoRoot 'src') "rs$year")
    $dataDir = ConvertTo-ComposePath ([string]$Version.dataDir)
    $target = "C:/ProgramData/Autodesk/Revit Server $year/Projects"
    $portLines = @("      - $(ConvertTo-YamlSingleQuoted "$([int]$Version.hostPort):80")")

    # Revit connects over WCF net.tcp on 808, not over HTTP. Without this
    # mapping Revit fails with "TCP 10061 connection refused" even though the
    # admin web page answers perfectly well through the proxy.
    $servesRevit = $false
    if ($Version.PSObject.Properties.Match('revitClients').Count -gt 0) {
        $servesRevit = [bool]$Version.revitClients
    }
    if ($servesRevit) {
        $portLines += "      - $(ConvertTo-YamlSingleQuoted '808:808')"
    }

    # Long-syntax bind mount: the short "src:dst" form has to be split on ':',
    # which is ambiguous when both sides start with a Windows drive letter.
    $lines = @(
        '# Generated by the Revit Server Stack control panel. Edit it through the panel UI.',
        '# Manual edits here are overwritten on the next save.',
        'services:',
        "  rs${year}:",
        "    build: $(ConvertTo-YamlSingleQuoted $buildContext)",
        "    container_name: rs${year}",
        '    ports:'
    ) + $portLines + @(
        '    volumes:',
        '      - type: bind',
        "        source: $(ConvertTo-YamlSingleQuoted $dataDir)",
        "        target: $(ConvertTo-YamlSingleQuoted $target)",
        ''
    )

    $path = Get-VersionComposePath -ComposeDir $ComposeDir -Year $year
    Write-TextFileUtf8 -Path $path -Content ($lines -join "`n") -WithCrLf
    return $path
}

# The proxy container reaches the Windows containers through the host ports they
# publish. On this machine that is host.docker.internal; with a remote engine it
# is the address of that machine, as the proxy container sees it.
function Get-ProxyUpstreamHost {
    param([Parameter(Mandatory = $true)]$Config)

    $engine = Get-EngineInfo -Context ([string]$Config.windowsContext) -HostOverride ([string]$Config.windowsHost)
    if ($engine.HostInvalid) { return 'host.docker.internal' }
    if (@('localhost', '127.0.0.1', '[::1]') -contains $engine.Host.ToLowerInvariant()) { return 'host.docker.internal' }
    return $engine.Host
}

function Write-ProxyNginxConf {
    param(
        [Parameter(Mandatory = $true)]$Config,
        [Parameter(Mandatory = $true)][string]$ComposeDir,
        [string]$UpstreamHost = 'host.docker.internal'
    )

    # The value is written into nginx.conf as it is.
    if (-not (Test-HostName $UpstreamHost)) { throw "Недопустимый адрес для nginx: $UpstreamHost" }

    $enabled = @($Config.versions | Where-Object { $_.enabled })

    $upstreams = @()
    $locations = @()
    foreach ($version in $enabled) {
        $year = [int]$version.year
        $port = [int]$version.hostPort
        $upstreams += "    upstream rs${year} { server ${UpstreamHost}:${port}; }"
        $locations += '        location ~* /[A-Za-z]+' + $year + '(/|$) { proxy_pass http://rs' + $year + '; }'
    }

    if ($upstreams.Count -eq 0) {
        $upstreams += '    # no versions enabled in the panel'
    }
    if ($locations.Count -eq 0) {
        $locations += '        # no versions enabled in the panel'
    }

    $head = @(
        '# Generated by the Revit Server Stack control panel. Manual edits are overwritten.',
        'worker_processes auto;',
        'events { worker_connections 1024; }',
        '',
        'http {',
        '    # Revit central models are large -> never cap or buffer the body.',
        '    client_max_body_size 0;',
        '    proxy_http_version 1.1;',
        '    proxy_request_buffering off;',
        '    proxy_buffering off;',
        '    proxy_read_timeout 3600s;',
        '    proxy_send_timeout 3600s;',
        '    send_timeout 3600s;',
        ''
    )

    $middle = @(
        '',
        '    server {',
        '        listen 80 default_server;',
        '        server_name _;',
        '',
        '        proxy_set_header Host              $host;',
        '        proxy_set_header X-Forwarded-For   $remote_addr;',
        '        proxy_set_header X-Forwarded-Proto $scheme;',
        '',
        '        # Every Revit Server IIS app embeds the version year in its path',
        '        # (RevitServerAdmin2022, AdminService2022, LocalService2022, ...).',
        '        # Route purely by that year so one host:80 serves every version.'
    )

    $tail = @(
        '',
        '        location = / {',
        '            default_type text/plain;',
        '            return 200 "Revit Server proxy is up. Point Revit at this host name/IP with no port.\n";',
        '        }',
        '    }',
        '}',
        ''
    )

    $lines = $head + $upstreams + $middle + $locations + $tail

    $path = Get-ProxyNginxPath -ComposeDir $ComposeDir
    Write-TextFileUtf8 -Path $path -Content ($lines -join "`n") -WithCrLf
    return $path
}

function Write-ProxyCompose {
    param(
        [Parameter(Mandatory = $true)]$Config,
        [Parameter(Mandatory = $true)][string]$ComposeDir
    )

    $portMapping = "$([int]$Config.proxy.port):80"

    # nginx.conf travels inside the compose file, as an environment variable that
    # the container writes out itself. A bind mount of the generated file would
    # name a path on the machine of the engine, which is not this machine when
    # the engine is remote. "$" is doubled because compose interpolates it.
    $nginx = (Read-TextFileUtf8 (Get-ProxyNginxPath -ComposeDir $ComposeDir)).Replace("`r`n", "`n").TrimEnd()
    $nginxLines = @($nginx.Replace('$', '$$') -split "`n" | ForEach-Object { if ($_.Length -gt 0) { "        $_" } else { '' } })
    $start = 'printf ''%s\n'' "$$NGINX_CONF" > /etc/nginx/nginx.conf && exec nginx -g ''daemon off;'''

    $lines = @(
        '# Generated by the Revit Server Stack control panel. Manual edits are overwritten.',
        '# Runs on a Linux docker engine, this machine or a remote one, and reaches the',
        '# Windows rs<year> containers through the host ports they publish.',
        'services:',
        '  revit-proxy:',
        "    image: $(ConvertTo-YamlSingleQuoted ([string]$Config.proxy.image))",
        '    container_name: revit-proxy',
        '    restart: unless-stopped',
        '    ports:',
        "      - $(ConvertTo-YamlSingleQuoted $portMapping)",
        '    environment:',
        '      NGINX_CONF: |'
    ) + $nginxLines + @(
        '    command:',
        '      - /bin/sh',
        '      - -c',
        "      - $(ConvertTo-YamlSingleQuoted $start)",
        '    extra_hosts:',
        "      - 'host.docker.internal:host-gateway'",
        ''
    )

    $path = Get-ProxyComposePath -ComposeDir $ComposeDir
    Write-TextFileUtf8 -Path $path -Content ($lines -join "`n") -WithCrLf
    return $path
}

# Regenerates every artefact the panel drives docker with.
function Update-GeneratedFiles {
    param(
        [Parameter(Mandatory = $true)]$Config,
        [Parameter(Mandatory = $true)][string]$RepoRoot,
        [Parameter(Mandatory = $true)][string]$ComposeDir
    )

    if (-not (Test-Path -LiteralPath $ComposeDir)) {
        New-Item -ItemType Directory -Path $ComposeDir -Force | Out-Null
    }

    $written = @()
    foreach ($version in $Config.versions) {
        $written += Write-VersionCompose -Config $Config -Version $version -RepoRoot $RepoRoot -ComposeDir $ComposeDir
    }
    $written += Write-ProxyNginxConf -Config $Config -ComposeDir $ComposeDir -UpstreamHost (Get-ProxyUpstreamHost -Config $Config)
    $written += Write-ProxyCompose -Config $Config -ComposeDir $ComposeDir
    return $written
}
